export function learnQuiz(conceptId: string): Quiz {
  const specs = QUIZZES[conceptId] ?? [];
  return {
    conceptId,
    contentVersion: 1,
    questions: specs.map((spec, i) => ({ id: i + 1, question: spec.question, options: spec.options.map((o, j) => ({ id: j + 1, text: o.text })) })),
  };
}

export function gradeQuiz(conceptId: string, answers: Record<string, number>): QuizResult["items"] {
  const specs = QUIZZES[conceptId] ?? [];
  return specs.map((spec, i) => {
    const quizId = i + 1;
    const selectedOptionId = answers[String(quizId)] ?? 0;
    const correctOptionId = spec.options.findIndex(o => o.correct) + 1;
    const selected = spec.options[selectedOptionId - 1];
    const correct = selectedOptionId === correctOptionId;
    return {
      quizId, correct, selectedOptionId, correctOptionId,
      feedback: selected?.feedback ?? "답을 고르지 않았다.",
      explanation: spec.explanation,
      nextAction: spec.nextAction,
    };
  });
}

// ── 내 학습(메모리). 로그인 사용자별 제출 기록 ────────────────────────────────
interface Progress { bestScore: number | null; lastAttemptedAt: string | null; wrongQuizIds: number[] }
const progressByUser = new Map<number, Map<string, Progress>>();

function seedProgress(): Map<string, Progress> {
  // learner@example.com 의 시드: 1·2단원 완료, 3단원 50점(2·4번 오답). 새 사용자도 같은 시드로 시작한다.
  const map = new Map<string, Progress>();
  for (const c of CONCEPTS) {
    if (c.orderNo <= 2) map.set(c.id, { bestScore: 100, lastAttemptedAt: "2026-10-29T10:00:00Z", wrongQuizIds: [] });
    else if (c.orderNo === 3) map.set(c.id, { bestScore: 50, lastAttemptedAt: "2026-10-29T10:20:00Z", wrongQuizIds: [2, 4] });
  }
  return map;
}
function progressOf(user: User): Map<string, Progress> {
  let map = progressByUser.get(user.id);
  if (!map) { map = seedProgress(); progressByUser.set(user.id, map); }
  return map;
}

export function recordAttempt(user: User, conceptId: string, score: number, wrongQuizIds: number[]) {
  const map = progressOf(user);
  const prev = map.get(conceptId);
  map.set(conceptId, {
    bestScore: Math.max(prev?.bestScore ?? 0, score),
    lastAttemptedAt: new Date().toISOString(),
    wrongQuizIds,
  });
}

export function myLearningOf(user: User): MyLearning {
  const map = progressOf(user);
  const concepts = CONCEPTS.map(c => {
    const p = map.get(c.id);
    return {
      conceptId: c.id, title: c.title,
      bestScore: p?.bestScore ?? null,
      completed: (p?.bestScore ?? 0) >= 80,
      lastAttemptedAt: p?.lastAttemptedAt ?? null,
      wrongQuizIds: p?.wrongQuizIds ?? [],
    };
  });
  const next = concepts.find(c => !c.completed);
  return { completedCount: concepts.filter(c => c.completed).length, totalCount: concepts.length, concepts, nextConceptId: next?.conceptId ?? null };
}

