export const LEARN_TERMS: TermSummary[] = TERM_SPECS.map(({ slug, term, english, category, definition }) => ({ slug, term, english, category, definition }));
export const TERM_CATEGORIES = ["업무", "금리·한도", "심사", "상환", "연체·건전성", "운영"];

export function learnTerm(slug: string): Term | null {
  const spec = TERM_SPECS.find(t => t.slug === slug);
  if (!spec) return null;
  const related = (spec.related ?? []).map(s => LEARN_TERMS.find(t => t.slug === s)).filter((t): t is TermSummary => !!t);
  return {
    slug: spec.slug, term: spec.term, english: spec.english, category: spec.category, definition: spec.definition,
    formula: spec.formula ?? null,
    example: spec.example ?? null,
    caution: spec.caution ?? "교육용 정의이며 실제 금융회사의 약관·심사 기준과 다를 수 있다.",
    related,
    conceptIds: spec.conceptIds ?? [],
    sourceUrl: spec.sourceUrl ?? "https://fine.fss.or.kr",
    sourceCheckedOn: CHECKED_ON,
  };
}

export function filterTerms(params: { q?: string | null; category?: string | null; initial?: string | null }): TermSummary[] {
  let terms = LEARN_TERMS;
  if (params.category) terms = terms.filter(t => t.category === params.category);
  if (params.initial) terms = terms.filter(t => initialOf(t.term) === params.initial!.toUpperCase());
  const q = params.q?.trim().toLowerCase();
  if (q) terms = terms.filter(t => t.term.toLowerCase().includes(q) || (t.english ?? "").toLowerCase().includes(q) || t.definition.toLowerCase().includes(q));
  return terms;
}

// ── 라우터. index.ts 가 학습·용어·방법론·내 학습 경로를 여기로 넘긴다 ─────────
export interface LearnMockResult { status: number; body: unknown; requestId: string }
let counter = 0;
const rid = () => `mock-learn-${String(++counter).padStart(4, "0")}`;
const ok = (body: unknown, status = 200): LearnMockResult => ({ status, body, requestId: rid() });
const fail = (status: number, code: string, message: string): LearnMockResult => { const requestId = rid(); return { status, body: { code, message, requestId }, requestId }; };

export function mockLearn(method: string, pathname: string, params: URLSearchParams, body: unknown, me: User | null): LearnMockResult | null {
  if (method === "GET" && pathname === "/me/learning") return me ? ok(myLearningOf(me)) : fail(401, "UNAUTHORIZED", "로그인이 필요해요. 다시 로그인한 뒤 시도해요.");
  if (method === "GET" && pathname === "/learning/concepts") return ok(CONCEPTS);
  if (method === "GET" && pathname === "/methodology") return ok(METHODOLOGY);

  const concept = pathname.match(/^\/learning\/concepts\/([^/]+)(\/quiz(\/attempts)?)?$/);
  if (concept) {
    const summary = CONCEPTS.find(c => c.id === concept[1]);
    if (!summary) return fail(404, "NOT_FOUND", "그 개념을 찾지 못했어요. 입문 과정 목차에서 다시 골라요.");
    if (!concept[2] && method === "GET") return ok(learnConcept(summary));
    if (concept[2] === "/quiz" && method === "GET") return ok(learnQuiz(summary.id));
    if (concept[3] && method === "POST") {
      const { contentVersion, answers } = (body ?? {}) as { contentVersion?: number; answers?: Record<string, number> };
      if (contentVersion !== 1) return fail(409, "CONFLICT", "문제 내용이 바뀌었어요. 문제를 다시 불러와요.");
      const items = gradeQuiz(summary.id, answers ?? {});
      const score = items.length ? Math.round(items.filter(i => i.correct).length / items.length * 100) : 0;
      const wrong = items.filter(i => !i.correct).map(i => i.quizId);
      if (me) recordAttempt(me, summary.id, score, wrong);
      return ok({ score, passed: score >= 80, saved: !!me, items } satisfies QuizResult);
    }
  }

  if (method === "GET" && pathname === "/glossary") return ok(filterTerms({ q: params.get("q"), category: params.get("category"), initial: params.get("initial") }));
  const term = pathname.match(/^\/glossary\/([^/]+)$/);
  if (term && method === "GET") {
    const found = learnTerm(decodeURIComponent(term[1]));
    return found ? ok(found) : fail(404, "NOT_FOUND", "그 용어를 찾지 못했어요. 용어 사전에서 검색해요.");
  }
  return null;
}
